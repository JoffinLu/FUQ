    ("manuscript/main_test.tex", "manuscript/main_test.tex"),
    ("manuscript/main_test.pdf", "manuscript/main_test.pdf"),
    ("manuscript/sn-jnl.cls", "manuscript/sn-jnl.cls"),
    ("manuscript/sn-basic.bst", "manuscript/sn-basic.bst"),
