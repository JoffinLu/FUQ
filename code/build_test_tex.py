"""Build the TEST (Springer, sn-jnl) version of the manuscript.

Reads manuscript/main.tex (generic article version), keeps the body verbatim and
replaces the preamble + front matter with the official Springer Nature LaTeX
template conventions (class sn-jnl, author-year "Basic" reference style, which is
what TEST uses).  The generic version stays as the canonical source.

    python code/build_test_tex.py            # writes manuscript/main_test.tex

Requires sn-jnl.cls and sn-basic.bst in manuscript/ (copied from tools/sn-jnl,
the official Springer Nature LaTeX template v2.1).
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MS = ROOT / "manuscript"
SRC = MS / "main.tex"
DST = MS / "main_test.tex"

PREAMBLE = r"""%% TEST (Springer) version, generated by code/build_test_tex.py from main.tex.
%% Official template: Springer Nature LaTeX Template v2.1 (sn-jnl.cls), class option
%% sn-basic = Springer Basic reference style (author-year), which is the style TEST uses.
\documentclass[pdflatex,sn-basic]{sn-jnl}

\usepackage{graphicx}
\usepackage{multirow}
\usepackage{amsmath,amssymb,amsthm,mathtools}
\usepackage{booktabs}
\usepackage{xcolor}
\usepackage{textcomp}
\usepackage{manyfoot}



\newtheorem{theorem}{Theorem}
\newtheorem{lemma}{Lemma}
\newtheorem{corollary}{Corollary}
\newtheorem{proposition}{Proposition}
\newtheorem{assumption}{Assumption}
\newtheorem{remark}{Remark}

\newcommand{\E}{\mathbb{E}}
\newcommand{\R}{\mathbb{R}}
\newcommand{\phidi}{\phi_{\mathrm{DI}}}
\newcommand{\phidm}{\phi_{\mathrm{DM}}}
\newcommand{\dhat}{\hat\Delta}
\newcommand{\tbar}{\bar\theta}
\newcommand{\Dp}{D'}
\newcommand{\Dt}{\tilde D}

\begin{document}

\title[Training, Evaluation and Constraint-Set Noise in Fairness UQ]{Separating Training, Evaluation and Constraint-Set Noise in Fairness Uncertainty Quantification}

\author*[1]{\fnm{Cenfa} \sur{Lu}}\email{joffin@163.com}

\affil*[1]{\orgdiv{School of Mathematics and Computational Science}, \orgname{Guilin University of Electronic Technology}, \orgaddress{\city{Guilin}, \postcode{541004}, \country{China}}}

\abstract{"""

SIGNAL = r"""}

\keywords{fairness auditing, uncertainty quantification, constrained stochastic optimization, online bootstrap, distribution-free inference}

\maketitle

"""

TAIL_PREFIX = "\\section{Introduction}"


def main() -> int:
    text = SRC.read_text(encoding="utf-8")

    # abstract: between \begin{abstract} and \end{abstract}
    m = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", text, re.S)
    if not m:
        raise SystemExit("abstract not found in main.tex")
    abstract = m.group(1).strip()

    # body: from \section{Introduction} to just before \bibliography{refs}
    start = text.index(TAIL_PREFIX)
    end = text.index("\\bibliography{refs}")
    body = text[start:end].rstrip()

    # Springer style: the back-matter block is called "Declarations" and its
    # items are set as standalone bold headings (\bmhead) rather than run-in
    # \paragraph heads.
    body = body.replace("\\section*{Statements}", "\\section*{Declarations}")
    body = re.sub(r"\\paragraph\{([^}]*)\}\s*", r"\\bmhead{\1}\n\n", body)

    out = PREAMBLE + abstract + SIGNAL + body + "\n\n\\bibliographystyle{sn-basic}\n\\bibliography{refs}\n\n\\end{document}\n"
    DST.write_text(out, encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)} ({len(out)} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

